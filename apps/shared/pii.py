_CAP = r'[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?'
_WORD_CAP = re.compile(_CAP)
_SURNAME = re.compile(
    r'[А-ЯЁ][а-яё]+(?:ов|ев|ёв|ин|ын|ова|ева|ёва|ина|ына|ский|цкий|ская|цкая|ко|ук|юк|ян|дзе|швили|ых|их)')
_PATRONYMIC = re.compile(
    r'[А-ЯЁ][а-яё]+(?:(?:ович|евич|ьич)(?:а|у|ем|е)?|(?:овн|евн|ичн)(?:а|ы|е|у|ой))')

# Падежные окончания имени: «Маше», «Ивану», «Анной» → именительный.
_ОКОНЧАНИЯ = (('ой', ('а', 'я')), ('ей', ('я', 'а', 'й')), ('ем', ('й', '')), ('ом', ('',)),
              ('е', ('а', 'я', '')), ('у', ('', 'а')), ('ю', ('я', 'й')), ('ы', ('а',)),
              ('и', ('я', 'а', 'й')), ('а', ('', 'й')), ('я', ('й',)))


def _это_имя(слово: str) -> bool:
    w = слово.lower()
    if w in _NAMES:
        return True
    for конец, замены in _ОКОНЧАНИЯ:
        if w.endswith(конец) and len(w) > len(конец) + 1:
            основа = w[:-len(конец)]
            if any(основа + z in _NAMES for z in замены):
                return True
    return False


class Обезличка:
    """Метки одного запроса: значение → метка и обратно."""

    def __init__(self):
        self._по_значению: dict[tuple[str, str], str] = {}
        self._значения: dict[str, str] = {}
        self._счёт: dict[str, int] = {}

    def __bool__(self) -> bool:
        return bool(self._значения)

    def метка(self, вид: str, значение: str) -> str:
        ключ = (вид, значение.strip().lower())
        if ключ in self._по_значению:
            return self._по_значению[ключ]
        n = self._счёт.get(вид, 0) + 1
        self._счёт[вид] = n
        m = f'[{вид}-{n}]'
        self._по_значению[ключ] = m
        self._значения[m] = значение
        return m

    # ── структурные данные ───────────────────────────────────────────────────

    def структурные(self, text: str) -> str:
        if not text or not isinstance(text, str):
            return text
        text = _EMAIL.sub(lambda m: self.метка('EMAIL', m.group(0)), text)
        text = _PASSPORT.sub(lambda m: m.group(1) + self.метка('ПАСПОРТ', m.group(2)), text)

        def карта(m):
            digits = re.sub(r'\D', '', m.group(0))
            if 13 <= len(digits) <= 19 and _luhn(digits):
                return self.метка('КАРТА', m.group(0))
            return m.group(0)
        text = _CARD.sub(карта, text)
        text = _PHONE.sub(lambda m: self.метка('ТЕЛЕФОН', m.group(0)), text)
        text = _ADDRESS.sub(lambda m: self.метка('АДРЕС', m.group(0)), text)
        text = _FLAT.sub(lambda m: self.метка('АДРЕС', m.group(0)), text)
        return text

    # ── имена ────────────────────────────────────────────────────────────────

    def имена(self, text: str, известные: Iterable[str] = ()) -> str:
        if not text or not isinstance(text, str):
            return text
        for имя in sorted({(n or '').strip() for n in известные if n and len(n.strip()) >= 3},
                          key=len, reverse=True):
            text = re.sub(r'(?<!\w)' + re.escape(имя) + r'(?!\w)',
                          lambda m: self.метка('ИМЯ', m.group(0)), text, flags=re.I)
            for часть in имя.split():
                if len(часть) >= 3:
                    text = re.sub(r'(?<!\w)' + re.escape(часть) + r'(?!\w)',
                                  lambda m: self.метка('ИМЯ', m.group(0)), text)

        # «Имя Фамилия», «Фамилия Имя Отчество», «Имя Отчество» — одним куском,
        # но только сами имена: «Спасибо Маше» → «Спасибо [ИМЯ-1]».
        шаблон = re.compile(rf'{_CAP}(?:\s+{_CAP}){{0,3}}')

        def кусок(m):
            слова = list(_WORD_CAP.finditer(m.group(0)))
            имя_или_отч = [i for i, w in enumerate(слова)
                           if _это_имя(w.group(0)) or _PATRONYMIC.fullmatch(w.group(0))]
            if not имя_или_отч:
                return m.group(0)
            lo, hi = min(имя_или_отч), max(имя_или_отч)
            # Фамилия рядом с именем — по типичному окончанию.
            if lo > 0 and _SURNAME.fullmatch(слова[lo - 1].group(0)):
                lo -= 1
            if hi + 1 < len(слова) and (_SURNAME.fullmatch(слова[hi + 1].group(0))
                                        or _PATRONYMIC.fullmatch(слова[hi + 1].group(0))):
                hi += 1
            a, b = слова[lo].start(), слова[hi].end()
            src = m.group(0)
            return src[:a] + self.метка('ИМЯ', src[a:b]) + src[b:]
        return шаблон.sub(кусок, text)

    # ── обратно ──────────────────────────────────────────────────────────────

    def вернуть(self, value: Any) -> Any:
        """Метки → исходные значения. Строки, списки и словари — вглубь."""
        if not self._значения:
            return value
        if isinstance(value, str):
            def back(m):
                ключ = f'[{m.group(1)}-{m.group(2)}]'
                return self._значения.get(ключ, m.group(0))
            return _PLACEHOLDER.sub(back, value)
        if isinstance(value, list):
            return [self.вернуть(v) for v in value]
        if isinstance(value, tuple):
            return tuple(self.вернуть(v) for v in value)
        if isinstance(value, dict):
            return {k: self.вернуть(v) for k, v in value.items()}
        return value



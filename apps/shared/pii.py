"""
Обезличивание текстов перед отправкой во внешний ИИ (OpenAI) — решение владельца
15.10.2026: уведомления РКН о трансграничной передаче нет, значит личные данные
гостей наружу не уходят.

Как устроено: личные данные заменяются метками (`[ТЕЛЕФОН-1]`, `[ИМЯ-2]`), а
в ответе модели метки подставляются обратно (`Обезличка.вернуть`). Сотрудник
видит полный разбор, модель — только метки. Одно и то же значение в рамках
одного запроса получает одну и ту же метку.

Два слоя:
  • `структурные` — телефоны, почта, номера карт (Луна), паспорта (только рядом
    со словом «паспорт»), адреса с улицей/домом/квартирой. Включается в общем
    транспорте `apps/shared/ai/openai_compat.py` для ВСЕХ обращений.
  • `имена` — имена по словарю + фамилия/отчество рядом, и явно переданные имена
    (автор жалобы). Только там, где текст — гостевой: разбор жалобы и звонка.
    В общем транспорте имена не трогаем: Чекапчику нужны имена сотрудников.

Выключатель — `AI_PII_REDACT` (по умолчанию включено).
"""

from __future__ import annotations

import os
import re
from typing import Any, Iterable

from django.conf import settings


def включено() -> bool:
    значение = getattr(settings, 'AI_PII_REDACT', None) or os.getenv('AI_PII_REDACT', 'on')
    return str(значение).strip().lower() not in ('off', '0', 'false', 'no')


_PHONE = re.compile(
    r'(?<![\w+])(?:\+7|8|7)[\s\-\(]*\d{3}[\s\-\)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)'
    r'|(?<![\w+])9\d{2}[\s\-]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}(?!\d)'
)
_EMAIL = re.compile(r'[\w.+\-]+@[\w\-]+(?:\.[\w\-]+)+')
_CARD = re.compile(r'(?<!\d)(?:\d[ \-]?){12,18}\d(?!\d)')
_PASSPORT = re.compile(
    r'(паспорт\w*[^\d\n]{0,25})(\d{2}\s?\d{2}[\s№N]*\d{6})(?!\d)', re.I)
_STREET = (r'(?:ул\.|улиц[аеыу]|пр-т|просп\.|проспект[ае]?|пер\.|переул(?:ок|ке)|б-р|бульвар[ае]?'
           r'|ш\.|шоссе|наб\.|набережн(?:ая|ой)|мкр\.?|микрорайон[ае]?|пл\.|площад[ьи])')
_ADDRESS = re.compile(
    _STREET + r'\s*[А-ЯЁA-Z0-9][\w\-]*(?:\s+[А-ЯЁ][\w\-]*){0,2}'
    r'(?:,?\s*(?:д\.|дом)?\s*\d+[а-яА-Я]?(?:/\d+)?)?'
    r'(?:,?\s*(?:кв\.|квартир[аеуы]|оф\.)\s*\d+)?',
    re.I)
_FLAT = re.compile(r'(?:кв\.|квартир[аеуы])\s*\d+', re.I)

_PLACEHOLDER = re.compile(r'\[?(ТЕЛЕФОН|EMAIL|КАРТА|ПАСПОРТ|АДРЕС|ИМЯ)-(\d+)\]?')


def _luhn(digits: str) -> bool:
    total, alt = 0, False
    for ch in reversed(digits):
        d = int(ch)
        if alt:
            d *= 2
            if d > 9:
                d -= 9
        total += d
        alt = not alt
    return total % 10 == 0



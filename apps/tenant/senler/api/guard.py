"""
Предохранитель аудитории для внешнего кабинета.

Зачем: между тем, как кабинет показал «получателей: N», и нажатием
«Отправить» состав ячейки RF-матрицы меняется сам по себе (гости приходят,
сегменты пересчитываются ночью). ЧП 2026-08-21: «рассылка на 1 ушла 612».
Поэтому кабинет обязан прислать expected_count — цифру, которую видел
человек, — а сервер пересчитывает аудиторию заново и сравнивает.

Инвариант: расхождение больше max(5, 10% от expected) В ЛЮБУЮ сторону —
отправка отклоняется (409), пользователь обновляет предпросмотр и
подтверждает заново. Допуск в обе стороны: «стало меньше» тоже означает,
что человек подтверждал не то, что уйдёт.

Функции чистые (без ORM и Django) — тестируются напрямую.
"""
from __future__ import annotations


def tolerance(expected) -> int:
    """
    Допустимое расхождение для показанной цифры expected.

    max(5, 10%) — чтобы мелкие ячейки (1-10 гостей) не блокировались
    естественным дрейфом на пару человек, а крупные не уезжали на сотни.
    """
    try:
        value = int(expected)
    except (TypeError, ValueError):
        return 5
    if value < 0:
        value = 0
    return max(5, int(value * 0.1))


def audience_changed(expected, actual) -> bool:
    """
    True — аудиторию нужно подтверждать заново (отправку блокируем).

    Некорректные/отсутствующие значения трактуются как «изменилась»:
    лучше лишний раз попросить подтверждение, чем отправить вслепую.
    """
    try:
        expected_n = int(expected)
        actual_n = int(actual)
    except (TypeError, ValueError):
        return True
    return abs(actual_n - expected_n) > tolerance(expected_n)
